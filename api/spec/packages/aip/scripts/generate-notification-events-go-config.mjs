// Writes the oapi-codegen configuration of every Notification Event Go package.
//
// Run after api/v3/openapi.yaml is written: event payloads may reuse v3 models,
// and the generated Go types alias the v3 ones instead of duplicating them.
//
// For every package in the notification events manifest this script writes,
// into the Go package directory:
//   - oapi-codegen.gen.yaml: the shared oapi-codegen.notification-events.yaml,
//     plus an Overlay path when the package aliases v3 models;
//   - overlay.gen.yaml: an OpenAPI Overlay that sets x-go-type on every alias.
//     It only affects code generation; the published events spec is unchanged.
//
// A schema becomes an alias only when the v3 document has a schema with the
// same name and identical content, and every schema it references is an alias
// too. A frozen copy that differs from v3, or that references one, stays a
// local type, so an alias can never change the payload's shape.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { isDeepStrictEqual } from 'node:util'
import { parse, stringify } from 'yaml'

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(pkgRoot, '../../../..')
const manifest = JSON.parse(
  readFileSync(
    join(pkgRoot, 'output/notification-events/_go/manifest.json'),
    'utf8',
  ),
)
const baseConfig = parse(
  readFileSync(join(pkgRoot, 'oapi-codegen.notification-events.yaml'), 'utf8'),
)
const v3Schemas = parse(
  readFileSync(join(repoRoot, 'api/v3/openapi.yaml'), 'utf8'),
).components.schemas

const v3Import = {
  path: 'github.com/openmeterio/openmeter/api/v3',
  name: 'apiv3',
}
const schemaRef = '#/components/schemas/'
const header =
  '# Code generated by api/spec/packages/aip/scripts/generate-notification-events-go-config.mjs, DO NOT EDIT.\n'

const refsOf = (node, refs = new Set()) => {
  if (Array.isArray(node)) {
    node.forEach((n) => refsOf(n, refs))
  } else if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref' && typeof value === 'string') {
        if (!value.startsWith(schemaRef)) {
          throw new Error(`unexpected non-local $ref ${value}`)
        }
        refs.add(value.slice(schemaRef.length))
      } else {
        refsOf(value, refs)
      }
    }
  }
  return refs
}

const aliasesOf = (schemas) => {
  const aliases = new Set(
    Object.keys(schemas).filter(
      (name) =>
        name in v3Schemas && isDeepStrictEqual(schemas[name], v3Schemas[name]),
    ),
  )
  // Drop aliases that reference a local type until none do.
  for (let changed = true; changed;) {
    changed = false
    for (const name of aliases) {
      if ([...refsOf(schemas[name])].some((ref) => !aliases.has(ref))) {
        aliases.delete(name)
        changed = true
      }
    }
  }
  return [...aliases].sort()
}

for (const entry of manifest.packages) {
  const goDir = join(repoRoot, entry.dir)
  const schemas =
    parse(readFileSync(join(repoRoot, entry.spec), 'utf8')).components
      ?.schemas ?? {}
  const aliases = aliasesOf(schemas)

  const config = structuredClone(baseConfig)
  const overlayFile = join(goDir, 'overlay.gen.yaml')
  if (aliases.length > 0) {
    for (const name of aliases) {
      // oapi-codegen derives the same identifier from the same component name
      // in both packages; anything else would need its name mapping here.
      if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) {
        throw new Error(`${entry.spec}: cannot alias schema ${name}`)
      }
    }
    writeFileSync(
      overlayFile,
      header +
        stringify({
          overlay: '1.0.0',
          info: {
            title: `Alias v3 models in ${entry.dir}`,
            version: '1.0.0',
          },
          actions: aliases.map((name) => ({
            target: `$.components.schemas.${name}`,
            update: {
              'x-go-type': `${v3Import.name}.${name}`,
              'x-go-type-import': v3Import,
            },
          })),
        }),
    )
    // go generate runs in the package directory.
    config['output-options'] = {
      ...config['output-options'],
      overlay: { path: 'overlay.gen.yaml' },
    }
  } else if (existsSync(overlayFile)) {
    rmSync(overlayFile)
  }
  writeFileSync(
    join(goDir, 'oapi-codegen.gen.yaml'),
    header + stringify(config),
  )
}
