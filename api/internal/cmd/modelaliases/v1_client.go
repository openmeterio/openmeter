package main

import (
	"bytes"
	"fmt"
	"go/token"
	"os"
	"os/exec"

	"golang.org/x/tools/imports"
)

// go generate runs the v1 client target from api/client/go.
const (
	v1ClientAPIPrefix   = "../../"
	v1CloudSpec         = v1ClientAPIPrefix + "openapi.cloud.yaml"
	v1CloudModelsFile   = v1ClientAPIPrefix + "models/cloud.gen.go"
	v1CloudModelsConfig = v1ClientAPIPrefix + "models/cloud.codegen.yaml"
)

func generateV1ClientAliases() error {
	server, err := readDeclarations(v1ClientAPIPrefix + serverModelsFile)
	if err != nil {
		return err
	}

	cmd := exec.Command("go", "tool", "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen",
		"--config="+v1CloudModelsConfig, v1CloudSpec)
	cmd.Stderr = os.Stderr
	source, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("generate Cloud models: %w", err)
	}

	cloud, err := declarations(v1CloudSpec, source)
	if err != nil {
		return err
	}

	extra, models, err := mergeV1CloudModels(server, cloud)
	if err != nil {
		return err
	}

	if err := os.WriteFile(v1CloudModelsFile, extra, 0o644); err != nil {
		return err
	}

	return v1Client.writeAliases(models)
}

// Keep Cloud-only definitions in their own file so their imports stay file-scoped.
// The legacy client exposes only the declarations from its Cloud spec.
func mergeV1CloudModels(server, cloud []declaration) ([]byte, []declaration, error) {
	shared := make(map[string]declaration, len(server))
	for _, d := range server {
		shared[d.name] = d
	}

	var extra bytes.Buffer
	fmt.Fprint(&extra, "// Code generated by modelaliases. DO NOT EDIT.\n\npackage models\n")
	for _, d := range cloud {
		if d.authKey {
			continue
		}

		if d.kind == token.IMPORT {
			fmt.Fprintf(&extra, "import %s\n", d.source)
			continue
		}

		if original, ok := shared[d.name]; ok {
			if d != original {
				return nil, nil, fmt.Errorf("%s: %s differs from shared models", v1CloudSpec, d.name)
			}

			continue
		}

		if d.kind == token.FUNC {
			fmt.Fprintln(&extra, d.source)
		} else {
			fmt.Fprintf(&extra, "%s %s\n", d.kind, d.source)
		}
	}

	// Trim imports used only by declarations already emitted in models.gen.go.
	formatted, err := imports.Process(v1CloudModelsFile, extra.Bytes(), nil)

	return formatted, cloud, err
}
