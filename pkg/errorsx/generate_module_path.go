//go:build ignore

package main

import (
	"fmt"
	"log"
	"os"
	"os/exec"
	"strings"
)

func main() {
	cmd := exec.Command("go", "list", "-f", "{{.Module.Path}}", ".")
	cmd.Stderr = os.Stderr
	output, err := cmd.Output()
	if err != nil {
		log.Fatal(err)
	}

	source := fmt.Sprintf("// Code generated by go generate. DO NOT EDIT.\n\npackage errorsx\n\nconst modulePath = %q\n", strings.TrimSpace(string(output)))
	if err := os.WriteFile("module_path.gen.go", []byte(source), 0o644); err != nil {
		log.Fatal(err)
	}
}
