package pgschemadiff

import (
	"testing"
	"time"

	"github.com/stretchr/testify/require"
	"github.com/stripe/pg-schema-diff/pkg/diff"
)

func TestDatabaseURL(t *testing.T) {
	// given:
	// - a development database URL with credentials and connection parameters
	// when:
	// - a URL is created for a disposable database
	// then:
	// - only the database name changes
	actual, err := databaseURL(
		"postgres://user:p%40ss@localhost:5432/postgres?sslmode=disable&search_path=public",
		"pgschemadiff_tmp_example",
	)
	require.NoError(t, err)
	require.Equal(
		t,
		"postgres://user:p%40ss@localhost:5432/pgschemadiff_tmp_example?sslmode=disable&search_path=public",
		actual,
	)
}

func TestRenderSQL(t *testing.T) {
	// given:
	// - a pg-schema-diff plan with timeout metadata and a migration hazard
	// when:
	// - the plan is rendered as a reviewable migration
	// then:
	// - the SQL preserves execution settings, hazard context, and statement order
	plan := diff.Plan{
		CurrentSchemaHash: "abc123",
		Statements: []diff.Statement{
			{
				DDL:         `ALTER TABLE "public"."billing_profiles" ADD CONSTRAINT "guard" FOREIGN KEY ("namespace", "tax_app_id") REFERENCES public."apps" ("namespace", "id")`,
				Timeout:     2 * time.Minute,
				LockTimeout: 3 * time.Second,
				Hazards: []diff.MigrationHazard{
					{Type: diff.MigrationHazardTypeAcquiresShareRowExclusiveLock, Message: "validating the foreign key takes a lock"},
				},
			},
		},
	}

	actual := string(RenderSQL(plan, true))

	require.Equal(t, `-- Generated by the pg-schema-diff proof of concept. Review before use.
-- Replay validation: passed.
-- Current schema hash: abc123

/*
Statement 0
  - ACQUIRES_SHARE_ROW_EXCLUSIVE_LOCK: validating the foreign key takes a lock
*/
SET SESSION statement_timeout = 120000;
SET SESSION lock_timeout = 3000;
ALTER TABLE "billing_profiles" ADD CONSTRAINT "guard" FOREIGN KEY ("namespace", "tax_app_id") REFERENCES "apps" ("namespace", "id");
`, actual)
}

func TestRenderSQLWithoutChanges(t *testing.T) {
	// given:
	// - an empty pg-schema-diff plan
	// when:
	// - the plan is rendered
	// then:
	// - the output clearly reports that the schema is already current
	actual := string(RenderSQL(diff.Plan{CurrentSchemaHash: "abc123"}, false))

	require.Equal(t, `-- Generated by the pg-schema-diff proof of concept. Review before use.
-- Replay validation: disabled.
-- Current schema hash: abc123
-- Schema matches the desired state.
`, actual)
}
