package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/openmeterio/openmeter/tools/migrate/viewgen"
)

func main() {
	var (
		schemaPath = flag.String("schema", "./openmeter/ent/schema", "path to the ent schema package")
		outPath    = flag.String("out", "./tools/migrate/views.sql", "output SQL file path")
	)
	flag.Parse()

	sql, err := viewgen.GenerateSQL(*schemaPath)
	if err != nil {
		exitf("%v", err)
	}

	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		exitf("create output dir: %v", err)
	}

	output := append([]byte("-- Code generated by viewgen, DO NOT EDIT.\n-- Regenerate with: make generate-view-sql\n"), sql...)
	if err := os.WriteFile(*outPath, output, 0o644); err != nil {
		exitf("write output: %v", err)
	}
}

func exitf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
