package namespacefks

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"slices"
	"strings"

	"entgo.io/ent/dialect/sql/schema"
)

const (
	namespaceColumn = "namespace"
	idColumn        = "id"

	postgresIdentifierMaxLength = 63
)

type GenerateInput struct {
	Tables      []*schema.Table
	ChildTables []string
}

func (i GenerateInput) Validate() error {
	var errs []error

	if len(i.Tables) == 0 {
		errs = append(errs, errors.New("tables are required"))
	}

	for _, table := range i.Tables {
		if table == nil {
			errs = append(errs, errors.New("tables cannot contain nil"))
		}
	}

	for _, table := range i.ChildTables {
		if strings.TrimSpace(table) == "" {
			errs = append(errs, errors.New("child table names cannot be empty"))
		}
	}

	return errors.Join(errs...)
}

type namespaceForeignKey struct {
	ChildTable       string
	ForeignKeyColumn string
	OriginalSymbol   string
	ParentTable      string
}

func Generate(input GenerateInput) ([]byte, error) {
	if err := input.Validate(); err != nil {
		return nil, fmt.Errorf("invalid namespace foreign key generation input: %w", err)
	}

	tablesByName := make(map[string]*schema.Table, len(input.Tables))
	for _, table := range input.Tables {
		tablesByName[table.Name] = table
	}

	includedChildTables := make(map[string]struct{}, len(input.ChildTables))
	for _, table := range input.ChildTables {
		includedChildTables[table] = struct{}{}
		if _, ok := tablesByName[table]; !ok {
			return nil, fmt.Errorf("child table %q not found", table)
		}
	}

	var foreignKeys []namespaceForeignKey
	parents := make(map[string]*schema.Table)

	for _, child := range input.Tables {
		if len(includedChildTables) > 0 {
			if _, ok := includedChildTables[child.Name]; !ok {
				continue
			}
		}

		if !child.HasColumn(namespaceColumn) {
			continue
		}

		for _, foreignKey := range child.ForeignKeys {
			if !isNamespaceForeignKeyCandidate(child, foreignKey) {
				continue
			}

			foreignKeys = append(foreignKeys, namespaceForeignKey{
				ChildTable:       child.Name,
				ForeignKeyColumn: foreignKey.Columns[0].Name,
				OriginalSymbol:   foreignKey.Symbol,
				ParentTable:      foreignKey.RefTable.Name,
			})
			parents[foreignKey.RefTable.Name] = foreignKey.RefTable
		}
	}

	slices.SortFunc(foreignKeys, func(left, right namespaceForeignKey) int {
		if byChild := strings.Compare(left.ChildTable, right.ChildTable); byChild != 0 {
			return byChild
		}

		return strings.Compare(left.ForeignKeyColumn, right.ForeignKeyColumn)
	})

	parentNames := make([]string, 0, len(parents))
	for parentName := range parents {
		parentNames = append(parentNames, parentName)
	}
	slices.Sort(parentNames)

	var output bytes.Buffer
	output.WriteString("-- Code generated by make generate-namespace-fks; DO NOT EDIT.\n")
	output.WriteString("-- The original Ent foreign keys remain responsible for relationship lifecycle actions.\n")
	output.WriteString("-- These additive constraints only enforce namespace equality.\n")
	if len(input.ChildTables) > 0 {
		selectedTables := slices.Clone(input.ChildTables)
		slices.Sort(selectedTables)
		fmt.Fprintf(&output, "-- Child tables: %s.\n", strings.Join(selectedTables, ", "))
	}

	for _, parentName := range parentNames {
		parent := parents[parentName]
		if hasUniqueNamespaceID(parent) {
			continue
		}

		fmt.Fprintf(
			&output,
			"\n-- Required by namespace guard foreign keys referencing %s.\nCREATE UNIQUE INDEX %s ON %s (%s, %s);\n",
			quoteIdentifier(parent.Name),
			quoteIdentifier(postgresIdentifier(parent.Name+"_namespace_id_key")),
			quoteIdentifier(parent.Name),
			quoteIdentifier(namespaceColumn),
			quoteIdentifier(idColumn),
		)
	}

	for _, foreignKey := range foreignKeys {
		fmt.Fprintf(
			&output,
			"\n-- Extends Ent foreign key %s with namespace equality.\nALTER TABLE %s\n  ADD CONSTRAINT %s\n  FOREIGN KEY (%s, %s)\n  REFERENCES %s (%s, %s)\n  ON UPDATE NO ACTION\n  ON DELETE NO ACTION;\n",
			quoteIdentifier(foreignKey.OriginalSymbol),
			quoteIdentifier(foreignKey.ChildTable),
			quoteIdentifier(postgresIdentifier(strings.Join([]string{
				foreignKey.ChildTable,
				strings.TrimSuffix(foreignKey.ForeignKeyColumn, "_id"),
				"namespace_guard_fk",
			}, "_"))),
			quoteIdentifier(namespaceColumn),
			quoteIdentifier(foreignKey.ForeignKeyColumn),
			quoteIdentifier(foreignKey.ParentTable),
			quoteIdentifier(namespaceColumn),
			quoteIdentifier(idColumn),
		)
	}

	return output.Bytes(), nil
}

func isNamespaceForeignKeyCandidate(child *schema.Table, foreignKey *schema.ForeignKey) bool {
	if foreignKey == nil || foreignKey.RefTable == nil {
		return false
	}

	if len(foreignKey.Columns) != 1 || len(foreignKey.RefColumns) != 1 {
		return false
	}

	if foreignKey.Columns[0].Name == namespaceColumn || foreignKey.RefColumns[0].Name != idColumn {
		return false
	}

	if !foreignKey.RefTable.HasColumn(namespaceColumn) {
		return false
	}

	return !hasNamespaceForeignKey(child, foreignKey)
}

func hasNamespaceForeignKey(child *schema.Table, candidate *schema.ForeignKey) bool {
	for _, foreignKey := range child.ForeignKeys {
		if foreignKey == nil || foreignKey.RefTable == nil || foreignKey.RefTable.Name != candidate.RefTable.Name {
			continue
		}

		if columnNamesEqual(foreignKey.Columns, namespaceColumn, candidate.Columns[0].Name) &&
			columnNamesEqual(foreignKey.RefColumns, namespaceColumn, idColumn) {
			return true
		}
	}

	return false
}

func hasUniqueNamespaceID(table *schema.Table) bool {
	if columnNamesEqual(table.PrimaryKey, namespaceColumn, idColumn) {
		return true
	}

	for _, index := range table.Indexes {
		if !index.Unique || !columnNamesEqual(index.Columns, namespaceColumn, idColumn) {
			continue
		}

		if index.Annotation == nil || index.Annotation.Where == "" {
			return true
		}
	}

	return false
}

func columnNamesEqual(columns []*schema.Column, expected ...string) bool {
	if len(columns) != len(expected) {
		return false
	}

	for index, column := range columns {
		if column == nil || column.Name != expected[index] {
			return false
		}
	}

	return true
}

func quoteIdentifier(identifier string) string {
	return `"` + strings.ReplaceAll(identifier, `"`, `""`) + `"`
}

func postgresIdentifier(identifier string) string {
	if len(identifier) <= postgresIdentifierMaxLength {
		return identifier
	}

	hash := sha256.Sum256([]byte(identifier))
	suffix := hex.EncodeToString(hash[:4])
	prefixLength := postgresIdentifierMaxLength - len(suffix) - 1

	return strings.TrimRight(identifier[:prefixLength], "_") + "_" + suffix
}
