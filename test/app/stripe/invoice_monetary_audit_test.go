// TestMonetaryAuditCreateRetryPreservesProviderTotal exercises the production
// Stripe app and HTTP client against a deterministic provider transport. The
// invoice itself is produced and reloaded through the real billing service.
//
// An invoice owes USD 100 - 40 discount = 60. Stripe accepts the first invoice
// item, rejects the second before executing it, and accepts a subsequent retry.
// UpsertStandardInvoice promises idempotence, and CreateInvoice uses a stable
// invoice idempotency key. The individual AddInvoiceLines requests currently
// have no stable application-level keys, so retry re-adds the successful prefix.
// With the current discount-first ordering, the successful retry leaves Stripe
// at 100 - 40 - 40 = 20 while OpenMeter still records USD 60. This establishes a
// provider subtotal discrepancy, not finalized undercollection: billing's
// finalizeInvoice performs another upsert, and a successful update can remove
// the orphaned duplicate before finalization. TestStripeFinalizationMonetaryAudit
// follows that lifecycle and demonstrates that the current update instead uses
// invoice-line IDs on invoice-item endpoints, blocking approval before cleanup.
// This test isolates the earlier idempotence contract from that separate defect.
// Stripe's request-key contract: https://docs.stripe.com/api/idempotent_requests.
//
// The transport honors successful Stripe idempotency keys, including any keys
// generated by the SDK. No live Stripe account or network connection is used.
// Reproduce: POSTGRES_HOST=127.0.0.1 go test -tags=dynamic ./test/app/stripe
// -run TestStripeInvoicing/TestMonetaryAuditCreateRetryPreservesProviderTotal -count=1 -v
func (s *StripeInvoiceTestSuite) TestMonetaryAuditCreateRetryPreservesProviderTotal() {
	// Given a persisted, discounted invoice with an independently known amount.
	ctx := s.T().Context()
	namespace := s.GetUniqueNamespace("stripe-retry-monetary-audit")
	period := timeutil.ClosedPeriod{
		From: time.Date(2026, time.January, 1, 0, 0, 0, 0, time.UTC),
		To:   time.Date(2026, time.January, 2, 0, 0, 0, 0, time.UTC),
	}
	clock.FreezeTime(period.To.Add(time.Hour))
	defer clock.UnFreeze()

	sandboxApp := s.InstallSandboxApp(s.T(), namespace)
	s.ProvisionBillingProfile(ctx, namespace, sandboxApp.GetID(), billingtest.WithManualApproval())
	s.TaxCodeEnv.ProvisionProviderDefaultTaxCode(s.T(), namespace)
	customerEntity := s.CreateTestCustomer(namespace, "stripe-retry-monetary-audit")

	_, err := s.BillingService.CreatePendingInvoiceLines(ctx, billing.CreatePendingInvoiceLinesInput{
		Customer: customerEntity.GetID(),
		Currency: "USD",
		Lines: billing.NewCreatePendingInvoiceLines([]billing.GatheringLine{
			billing.NewFlatFeeGatheringLine(billing.NewFlatFeeLineInput{
				Namespace:     namespace,
				Period:        period,
				InvoiceAt:     period.To,
				ManagedBy:     billing.ManuallyManagedLine,
				Name:          "Synthetic discounted service",
				PerUnitAmount: alpacadecimal.NewFromInt(100),
				PaymentTerm:   productcatalog.InArrearsPaymentTerm,
				RateCardDiscounts: billing.Discounts{
					Percentage: &billing.PercentageDiscount{
						PercentageDiscount: productcatalog.PercentageDiscount{
							Percentage: models.NewPercentage(40),
						},
					},
				},
			}),
		}),
	})
	s.Require().NoError(err)

	invoices, err := s.BillingService.InvoicePendingLines(ctx, billing.InvoicePendingLinesInput{
		Customer: customerEntity.GetID(),
		AsOf:     lo.ToPtr(period.To),
	})
	s.Require().NoError(err)
	s.Require().Len(invoices, 1)

	persistedInvoice, err := s.BillingService.GetStandardInvoiceById(ctx, billing.GetStandardInvoiceByIdInput{
		Invoice: invoices[0].GetInvoiceID(),
		Expand:  billing.StandardInvoiceExpandAll,
	})
	s.Require().NoError(err)
	s.Require().Equal(60.0, persistedInvoice.Totals.Total.InexactFloat64())
	s.Require().Empty(persistedInvoice.ValidationIssues)

	installedApp, err := s.Fixture.setupApp(ctx, namespace)
	s.Require().NoError(err)
	_, err = s.Fixture.setupAppCustomerData(ctx, installedApp, customerEntity)
	s.Require().NoError(err)
	installedStripeApp, ok := installedApp.(stripeapp.App)
	s.Require().True(ok)

	provider := &stripeMonetaryAuditTransport{
		failItemAttempt: 2,
		items:           make(map[string][]*stripe.InvoiceItem),
		responses:       make(map[string][]byte),
	}
	previousHTTPClient := stripe.GetBackendWithConfig(stripe.APIBackend, &stripe.BackendConfig{}).(*stripe.BackendImplementation).HTTPClient
	stripe.SetHTTPClient(&http.Client{Transport: provider})
	defer stripe.SetHTTPClient(previousHTTPClient)

	stripeInvoicingApp, err := stripeapp.New(installedStripeApp.Meta, stripeapp.AppConfig{
		Logger:                 omtestutils.NewDiscardLogger(s.T()),
		AppService:             s.AppService,
		BillingService:         s.BillingService,
		StripeAppClientFactory: stripeclient.NewStripeAppClient,
		StripeAppService:       s.AppStripeService,
		SecretService:          s.SecretService,
	})
	s.Require().NoError(err)

	// When adding the second item fails and the unchanged invoice is retried.
	failedResult, err := stripeInvoicingApp.UpsertStandardInvoice(ctx, persistedInvoice)
	s.Require().Error(err)
	s.Require().Nil(failedResult)
	s.Require().Equal(1, provider.invoiceCount)
	s.Require().Len(provider.items["in_monetary_audit_1"], 1)
	s.Require().Empty(persistedInvoice.ExternalIDs.Invoicing)

	retryResult, err := stripeInvoicingApp.UpsertStandardInvoice(ctx, persistedInvoice)
	s.Require().NoError(err)
	stripeInvoiceID, ok := retryResult.GetExternalID()
	s.Require().True(ok)
	s.Require().Equal("in_monetary_audit_1", stripeInvoiceID)
	s.Require().Equal(1, provider.invoiceCount, "invoice creation itself is idempotent")

	// Then the successfully synchronized subtotal must match OpenMeter's USD 60.
	providerTotal := int64(0)
	for _, item := range provider.items[stripeInvoiceID] {
		providerTotal += item.Amount
		s.T().Logf("provider item=%s type=%s amount_minor_units=%d", item.ID, item.Metadata["om_line_type"], item.Amount)
	}

	s.Equal(int64(6000), providerTotal, "a successful prefix of invoice items must not be added twice after retry")
}

// stripeMonetaryAuditTransport models invoice synchronization and finalization,
// including successful-request idempotency and distinct line/item IDs. Its
// one injected rejection happens before executing the item request, so a later
// application retry can succeed after the provider-side condition is repaired.
type stripeMonetaryAuditTransport struct {
	failItemAttempt int
	itemAttempts    int
	invoiceCount    int
	finalizeCalls   int
	currency        stripe.Currency
	updateItemIDs   []string
	deleteItemIDs   []string
	invoices        map[string]*stripe.Invoice
	items           map[string][]*stripe.InvoiceItem
	responses       map[string][]byte
}

func (p *stripeMonetaryAuditTransport) RoundTrip(request *http.Request) (*http.Response, error) {
	if err := request.ParseForm(); err != nil {
		return nil, fmt.Errorf("parsing Stripe request: %w", err)
	}

	idempotencyKey := request.Header.Get("Idempotency-Key")
	cacheKey := request.Method + " " + request.URL.Path + " " + idempotencyKey
	if idempotencyKey != "" {
		if response, ok := p.responses[cacheKey]; ok {
			return stripeMonetaryAuditResponse(request, http.StatusOK, response), nil
		}
	}

	var payload any
	status := http.StatusOK

	switch {
	case request.Method == http.MethodGet && request.URL.Path == "/v1/customers/"+defaultStripeCustomerID:
		payload = &stripe.Customer{
			ID:    defaultStripeCustomerID,
			Email: "synthetic@example.com",
			InvoiceSettings: &stripe.CustomerInvoiceSettings{
				DefaultPaymentMethod: &stripe.PaymentMethod{
					ID: "pm_monetary_audit",
					BillingDetails: &stripe.PaymentMethodBillingDetails{
						Address: &stripe.Address{Country: "US"},
					},
				},
			},
		}

	case request.Method == http.MethodPost && request.URL.Path == "/v1/invoices":
		p.invoiceCount++
		p.currency = stripe.Currency(request.Form.Get("currency"))
		invoice := &stripe.Invoice{
			ID:       fmt.Sprintf("in_monetary_audit_%d", p.invoiceCount),
			Object:   "invoice",
			Customer: &stripe.Customer{ID: request.Form.Get("customer")},
			Currency: p.currency,
			Status:   stripe.InvoiceStatusDraft,
		}
		if p.invoices == nil {
			p.invoices = make(map[string]*stripe.Invoice)
		}

		p.invoices[invoice.ID] = invoice
		payload = invoice

	case request.Method == http.MethodPost && request.URL.Path == "/v1/invoiceitems":
		p.itemAttempts++
		if p.itemAttempts == p.failItemAttempt {
			return stripeMonetaryAuditResponse(request, http.StatusBadRequest, []byte(`{"error":{"type":"invalid_request_error","message":"synthetic provider condition before item creation"}}`)), nil
		}

		amount, err := strconv.ParseInt(request.Form.Get("amount"), 10, 64)
		if err != nil {
			return nil, fmt.Errorf("parsing Stripe amount: %w", err)
		}

		invoiceID := request.Form.Get("invoice")
		item := &stripe.InvoiceItem{
			ID:          fmt.Sprintf("ii_monetary_audit_%d", p.itemAttempts),
			Object:      "invoiceitem",
			Amount:      amount,
			Currency:    p.currency,
			Description: request.Form.Get("description"),
			Invoice:     &stripe.Invoice{ID: invoiceID},
			Metadata: map[string]string{
				"om_line_id":   request.Form.Get("metadata[om_line_id]"),
				"om_line_type": request.Form.Get("metadata[om_line_type]"),
			},
		}
		p.items[invoiceID] = append(p.items[invoiceID], item)
		payload = item

	case (request.Method == http.MethodPost || request.Method == http.MethodDelete) && strings.HasPrefix(request.URL.Path, "/v1/invoiceitems/"):
		itemID := strings.TrimPrefix(request.URL.Path, "/v1/invoiceitems/")
		if request.Method == http.MethodPost {
			p.updateItemIDs = append(p.updateItemIDs, itemID)
		} else {
			p.deleteItemIDs = append(p.deleteItemIDs, itemID)
		}

		// Stripe's /invoiceitems endpoint accepts the item's ii_ ID, never
		// the il_ ID returned by the invoice's lines endpoint. Use exact lookup.
		for invoiceID, items := range p.items {
			for idx, item := range items {
				if item.ID != itemID {
					continue
				}

				if request.Method == http.MethodDelete {
					p.items[invoiceID] = slices.Delete(items, idx, idx+1)
					payload = &stripe.InvoiceItem{ID: itemID, Deleted: true}
				} else {
					amount, err := strconv.ParseInt(request.Form.Get("amount"), 10, 64)
					if err != nil {
						return nil, fmt.Errorf("parsing updated Stripe amount: %w", err)
					}

					item.Amount = amount
					item.Description = request.Form.Get("description")
					payload = item
				}

				break
			}

			if payload != nil {
				break
			}
		}

		if payload == nil {
			status = http.StatusNotFound
			payload = map[string]any{"error": map[string]string{
				"type":    "invalid_request_error",
				"code":    "resource_missing",
				"param":   "id",
				"message": fmt.Sprintf("No such invoiceitem: '%s'", itemID),
			}}
		}

	case request.Method == http.MethodGet && strings.HasPrefix(request.URL.Path, "/v1/invoices/") && strings.HasSuffix(request.URL.Path, "/lines"):
		invoiceID := strings.TrimSuffix(strings.TrimPrefix(request.URL.Path, "/v1/invoices/"), "/lines")
		lines := lo.Map(p.items[invoiceID], func(item *stripe.InvoiceItem, _ int) *stripe.InvoiceLineItem {
			return &stripe.InvoiceLineItem{
				ID:          "il_" + item.ID,
				Object:      "line_item",
				Amount:      item.Amount,
				InvoiceItem: item,
				Metadata:    item.Metadata,
			}
		})
		payload = &stripe.InvoiceLineItemList{Data: lines}

	case request.Method == http.MethodPost && strings.HasPrefix(request.URL.Path, "/v1/invoices/") && strings.HasSuffix(request.URL.Path, "/finalize"):
		invoiceID := strings.TrimSuffix(strings.TrimPrefix(request.URL.Path, "/v1/invoices/"), "/finalize")
		invoice, ok := p.invoices[invoiceID]
		if !ok {
			return nil, fmt.Errorf("unexpected Stripe invoice finalization: %s", invoiceID)
		}

		p.finalizeCalls++
		invoice.Status = stripe.InvoiceStatusOpen
		invoice.Number = "SYNTHETIC-001"
		invoice.Total = p.invoiceTotal(invoiceID)
		invoice.PaymentIntent = &stripe.PaymentIntent{ID: "pi_monetary_audit"}
		payload = invoice

	case (request.Method == http.MethodPost || request.Method == http.MethodGet) && strings.HasPrefix(request.URL.Path, "/v1/invoices/"):
		invoiceID := strings.TrimPrefix(request.URL.Path, "/v1/invoices/")
		invoice, ok := p.invoices[invoiceID]
		if !ok {
			return nil, fmt.Errorf("unexpected Stripe invoice lookup: %s", invoiceID)
		}

		invoice.Total = p.invoiceTotal(invoiceID)
		payload = invoice

	default:
		return nil, fmt.Errorf("unexpected Stripe request: %s %s", request.Method, request.URL.Path)
	}

	body, err := json.Marshal(payload)
	if err != nil {
		return nil, fmt.Errorf("encoding Stripe response: %w", err)
	}

	if idempotencyKey != "" && status == http.StatusOK {
		p.responses[cacheKey] = body
	}

	return stripeMonetaryAuditResponse(request, status, body), nil
}

func (p *stripeMonetaryAuditTransport) invoiceTotal(invoiceID string) int64 {
	total := int64(0)
	for _, item := range p.items[invoiceID] {
		total += item.Amount
	}

	return total
}

func stripeMonetaryAuditResponse(request *http.Request, status int, body []byte) *http.Response {
	return &http.Response{
		StatusCode: status,
		Header:     http.Header{"Content-Type": []string{"application/json"}},
		Body:       io.NopCloser(bytes.NewReader(body)),
		Request:    request,
	}
}
