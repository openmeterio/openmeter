type (
	CreateSubscriptionRequest = plansubscription.CreateSubscriptionRequest
	// CreateSubscriptionHandlerRequest keeps a custom plan undecoded: mapping it may create Tax Codes
	// for legacy stripe.code values, which has to happen in the same transaction as the create.
	CreateSubscriptionHandlerRequest struct {
		CreateSubscriptionRequest
		CustomPlan *api.CustomPlanInput
	}

	CreateSubscriptionResponse = api.Subscription
	CreateSubscriptionHandler  = httptransport.Handler[CreateSubscriptionHandlerRequest, CreateSubscriptionResponse]
)

func (h *handler) CreateSubscription() CreateSubscriptionHandler {
	return httptransport.NewHandler(
		func(ctx context.Context, r *http.Request) (CreateSubscriptionHandlerRequest, error) {
			body := api.CreateSubscriptionJSONRequestBody{}

			if err := commonhttp.JSONRequestBodyDecoder(r, &body); err != nil {
				return CreateSubscriptionHandlerRequest{}, err
			}

			ns, err := h.resolveNamespace(ctx)
			if err != nil {
				return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to resolve namespace: %w", err)
			}

			// Any transformation function generated by the API will succeed if the body is serializable, so we have to check for the presence of
			// fields to determine what body type we're dealing with
			type testForCustomPlan struct {
				CustomPlan any `json:"customPlan"`
			}

			var t testForCustomPlan

			bodyBytes, err := json.Marshal(body)
			if err != nil {
				return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to marshal request body: %w", err)
			}

			if err := json.Unmarshal(bodyBytes, &t); err != nil {
				return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to unmarshal request body: %w", err)
			}

			if t.CustomPlan != nil {
				// Custom subscription creation
				parsedBody, err := body.AsCustomSubscriptionCreate()
				if err != nil {
					return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to decode request body: %w", err)
				}

				timing := subscription.Timing{
					Enum: lo.ToPtr(subscription.TimingImmediate),
				}
				if parsedBody.Timing != nil {
					timing, err = MapAPITimingToTiming(*parsedBody.Timing)
					if err != nil {
						return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to map timing: %w", err)
					}
				}

				// Get the customer
				cus, err := h.getCustomer(ctx, ns, parsedBody.CustomerId, parsedBody.CustomerKey)
				if err != nil {
					return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to get customer: %w", err)
				}

				// The plan, and the subscription name, description and metadata taken from it, are
				// filled in by the operation once the custom plan is mapped.
				return CreateSubscriptionHandlerRequest{
					CreateSubscriptionRequest: CreateSubscriptionRequest{
						WorkflowInput: subscriptionworkflow.CreateSubscriptionWorkflowInput{
							ChangeSubscriptionWorkflowInput: subscriptionworkflow.ChangeSubscriptionWorkflowInput{
								Timing:        timing,
								CostBasisMode: subscription.CostBasisMode(lo.FromPtr(parsedBody.CostBasisMode)),
							},
							Namespace:     ns,
							CustomerID:    cus.ID,
							BillingAnchor: parsedBody.BillingAnchor,
						},
					},
					CustomPlan: &parsedBody.CustomPlan,
				}, nil
			} else {
				// Plan subscription creation
				parsedBody, err := body.AsPlanSubscriptionCreate()
				if err != nil {
					return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to decode request body: %w", err)
				}

				plan := plansubscription.PlanInput{}
				plan.FromRef(&plansubscription.PlanRefInput{
					Key: parsedBody.Plan.Key,
				})

				timing := subscription.Timing{
					Enum: lo.ToPtr(subscription.TimingImmediate),
				}
				if parsedBody.Timing != nil {
					timing, err = MapAPITimingToTiming(*parsedBody.Timing)
					if err != nil {
						return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to map timing: %w", err)
					}
				}

				var settlementMode *productcatalog.SettlementMode
				if parsedBody.SettlementMode != nil {
					settlementMode = lo.ToPtr(productcatalog.SettlementMode(*parsedBody.SettlementMode))
				}

				// Get the customer
				customer, err := h.getCustomer(ctx, ns, parsedBody.CustomerId, parsedBody.CustomerKey)
				if err != nil {
					return CreateSubscriptionHandlerRequest{}, fmt.Errorf("failed to get customer: %w", err)
				}

				return CreateSubscriptionHandlerRequest{
					CreateSubscriptionRequest: CreateSubscriptionRequest{
						WorkflowInput: subscriptionworkflow.CreateSubscriptionWorkflowInput{
							ChangeSubscriptionWorkflowInput: subscriptionworkflow.ChangeSubscriptionWorkflowInput{
								Timing:      timing,
								Name:        lo.FromPtr(parsedBody.Name),
								Description: parsedBody.Description,
								MetadataModel: models.MetadataModel{
									Metadata: convert.DerefHeaderPtr[string](parsedBody.Metadata),
								},
								CostBasisMode: subscription.CostBasisMode(lo.FromPtr(parsedBody.CostBasisMode)),
							},
							Namespace:     ns,
							CustomerID:    customer.ID,
							BillingAnchor: parsedBody.BillingAnchor,
						},
						PlanInput:      plan,
						StartingPhase:  parsedBody.StartingPhase,
						SettlementMode: settlementMode,
					},
				}, nil
			}
		},
		func(ctx context.Context, request CreateSubscriptionHandlerRequest) (CreateSubscriptionResponse, error) {
			var resp CreateSubscriptionResponse

			// Plan-reference requests don't need the transaction, but running every request through it
			// keeps a single code path; the service joins this transaction anyway.
			err := h.TaxCodeResolver.WithResolver(ctx, func(ctx context.Context, resolver productcatalog.TaxCodeBackfillResolver) error {
				req := request.CreateSubscriptionRequest

				if request.CustomPlan != nil {
					planReq, err := CustomPlanToCreatePlanRequest(ctx, resolver, *request.CustomPlan, req.WorkflowInput.Namespace)
					if err != nil {
						return fmt.Errorf("failed to create plan request: %w", err)
					}

					req.PlanInput.FromInput(&planReq)

					// We map the plan name, description and metadata to the subscription's
					req.WorkflowInput.Name = planReq.Name
					req.WorkflowInput.Description = planReq.Description
					req.WorkflowInput.Metadata = planReq.Metadata
				}

				res, err := h.PlanSubscriptionService.Create(ctx, req)
				if err != nil {
					return err
				}

				resp = MapSubscriptionToAPI(res)

				return nil
			})

			return resp, err
		},
		commonhttp.JSONResponseEncoderWithStatus[CreateSubscriptionResponse](http.StatusCreated),
		httptransport.AppendOptions(
			h.Options,
			httptransport.WithOperationName("createSubscription"),
			httptransport.WithErrorEncoder(errorEncoder()),
		)...,
	)
}

// getCustomer gets a customer by ID or key.
func (h *handler) getCustomer(ctx context.Context, namespace string, id *string, key *string) (*customer.Customer, error) {
	var (
		cus *customer.Customer
		err error
	)

	switch {
	case id != nil && *id != "":
		cus, err = h.CustomerService.GetCustomer(ctx, customer.GetCustomerInput{
			CustomerID: &customer.CustomerID{
				ID:        *id,
				Namespace: namespace,
			},
		})
		if err != nil {
			return nil, fmt.Errorf("failed to lookup customer by id [namespace=%s customer.id=%s]: %w", namespace, *id, err)
		}

	case key != nil && *key != "":
		cus, err = h.CustomerService.GetCustomer(ctx, customer.GetCustomerInput{
			CustomerKey: &customer.CustomerKey{
				Key:       *key,
				Namespace: namespace,
			},
		})
		if err != nil {
			return nil, fmt.Errorf("failed to lookup customer by key [namespace=%s customer.id=%s]: %w", namespace, *key, err)
		}

	default:
		return nil, models.NewGenericValidationError(fmt.Errorf("customer id or key is required"))
	}

	if cus != nil && cus.IsDeleted() {
		return nil, models.NewGenericPreConditionFailedError(
			fmt.Errorf("customer is deleted [namespace=%s customer.id=%s]", cus.Namespace, cus.ID),
		)
	}

	return cus, err
}
