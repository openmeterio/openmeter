package httpdriver

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"

	"github.com/samber/lo"

	"github.com/openmeterio/openmeter/api"
	"github.com/openmeterio/openmeter/openmeter/productcatalog"
	plansubscription "github.com/openmeterio/openmeter/openmeter/productcatalog/subscription"
	"github.com/openmeterio/openmeter/openmeter/subscription"
	subscriptionworkflow "github.com/openmeterio/openmeter/openmeter/subscription/workflow"
	"github.com/openmeterio/openmeter/pkg/convert"
	"github.com/openmeterio/openmeter/pkg/framework/commonhttp"
	"github.com/openmeterio/openmeter/pkg/framework/transport/httptransport"
	"github.com/openmeterio/openmeter/pkg/models"
)

type (
	ChangeSubscriptionRequest = plansubscription.ChangeSubscriptionRequest
	// ChangeSubscriptionHandlerRequest keeps a custom plan undecoded for the same reason as
	// CreateSubscriptionHandlerRequest.
	ChangeSubscriptionHandlerRequest struct {
		ChangeSubscriptionRequest
		CustomPlan *api.CustomPlanInput
	}
	ChangeSubscriptionResponse = api.SubscriptionChangeResponseBody
	ChangeSubscriptionParams   = struct {
		ID string
	}
	ChangeSubscriptionHandler = httptransport.HandlerWithArgs[ChangeSubscriptionHandlerRequest, ChangeSubscriptionResponse, ChangeSubscriptionParams]
)

func (h *handler) ChangeSubscription() ChangeSubscriptionHandler {
	return httptransport.NewHandlerWithArgs(
		func(ctx context.Context, r *http.Request, params ChangeSubscriptionParams) (ChangeSubscriptionHandlerRequest, error) {
			var body api.ChangeSubscriptionJSONRequestBody

			if err := commonhttp.JSONRequestBodyDecoder(r, &body); err != nil {
				return ChangeSubscriptionHandlerRequest{}, err
			}

			ns, err := h.resolveNamespace(ctx)
			if err != nil {
				return ChangeSubscriptionHandlerRequest{}, err
			}

			// Any transformation function generated by the API will succeed if the body is serializable, so we have to check for the presence of
			// fields to determine what body type we're dealing with
			type testForCustomPlan struct {
				CustomPlan any `json:"customPlan"`
			}

			var t testForCustomPlan

			bodyBytes, err := json.Marshal(body)
			if err != nil {
				return ChangeSubscriptionHandlerRequest{}, fmt.Errorf("failed to marshal request body: %w", err)
			}

			if err := json.Unmarshal(bodyBytes, &t); err != nil {
				return ChangeSubscriptionHandlerRequest{}, fmt.Errorf("failed to unmarshal request body: %w", err)
			}

			if t.CustomPlan != nil {
				// Changing to a custom Plan
				parsedBody, err := body.AsCustomSubscriptionChange()
				if err != nil {
					return ChangeSubscriptionHandlerRequest{}, fmt.Errorf("failed to parse custom plan: %w", err)
				}

				timing, err := MapAPITimingToTiming(parsedBody.Timing)
				if err != nil {
					return ChangeSubscriptionHandlerRequest{}, fmt.Errorf("failed to map timing: %w", err)
				}

				// The plan, and the subscription name, description and metadata taken from it, are
				// filled in by the operation once the custom plan is mapped.
				return ChangeSubscriptionHandlerRequest{
					ChangeSubscriptionRequest: ChangeSubscriptionRequest{
						ID: models.NamespacedID{Namespace: ns, ID: params.ID},
						WorkflowInput: subscriptionworkflow.ChangeSubscriptionWorkflowInput{
							Timing:        timing,
							BillingAnchor: parsedBody.BillingAnchor,
							CostBasisMode: subscription.CostBasisMode(lo.FromPtr(parsedBody.CostBasisMode)),
						},
						RejectUnitConfig: true,
					},
					CustomPlan: &parsedBody.CustomPlan,
				}, nil
			} else {
				// Changing to a Plan
				parsedBody, err := body.AsPlanSubscriptionChange()
				if err != nil {
					return ChangeSubscriptionHandlerRequest{}, fmt.Errorf("failed to parse plan: %w", err)
				}

				planInp := plansubscription.PlanInput{}
				planInp.FromRef(&plansubscription.PlanRefInput{
					Key:     parsedBody.Plan.Key,
					Version: parsedBody.Plan.Version,
				})

				timing, err := MapAPITimingToTiming(parsedBody.Timing)
				if err != nil {
					return ChangeSubscriptionHandlerRequest{}, fmt.Errorf("failed to map timing: %w", err)
				}

				var settlementMode *productcatalog.SettlementMode
				if parsedBody.SettlementMode != nil {
					settlementMode = lo.ToPtr(productcatalog.SettlementMode(*parsedBody.SettlementMode))
				}

				return ChangeSubscriptionHandlerRequest{
					ChangeSubscriptionRequest: ChangeSubscriptionRequest{
						ID:        models.NamespacedID{Namespace: ns, ID: params.ID},
						PlanInput: planInp,
						WorkflowInput: subscriptionworkflow.ChangeSubscriptionWorkflowInput{
							Timing: timing,
							MetadataModel: models.MetadataModel{
								Metadata: convert.DerefHeaderPtr[string](parsedBody.Metadata),
							},
							Name:          lo.FromPtr(parsedBody.Name),
							Description:   parsedBody.Description,
							BillingAnchor: parsedBody.BillingAnchor,
							CostBasisMode: subscription.CostBasisMode(lo.FromPtr(parsedBody.CostBasisMode)),
						},
						StartingPhase:    parsedBody.StartingPhase,
						SettlementMode:   settlementMode,
						RejectUnitConfig: true,
					},
				}, nil
			}
		},
		func(ctx context.Context, request ChangeSubscriptionHandlerRequest) (ChangeSubscriptionResponse, error) {
			var resp ChangeSubscriptionResponse

			// Plan-reference requests don't need the transaction, but running every request through it
			// keeps a single code path; the service joins this transaction anyway.
			err := h.TaxCodeResolver.WithResolver(ctx, func(ctx context.Context, resolver productcatalog.TaxCodeBackfillResolver) error {
				req := request.ChangeSubscriptionRequest

				if request.CustomPlan != nil {
					planReq, err := CustomPlanToCreatePlanRequest(ctx, resolver, *request.CustomPlan, req.ID.Namespace)
					if err != nil {
						return fmt.Errorf("failed to create plan request: %w", err)
					}

					req.PlanInput.FromInput(&planReq)

					req.WorkflowInput.Name = planReq.Name
					req.WorkflowInput.Description = planReq.Description
					req.WorkflowInput.Metadata = planReq.Metadata
				}

				res, err := h.PlanSubscriptionService.Change(ctx, req)
				if err != nil {
					return err
				}

				// Inside the transaction so Tax Codes created for this request are visible.
				taxCodes, err := h.taxCodesForView(ctx, res.Next)
				if err != nil {
					return err
				}

				v, err := MapSubscriptionViewToAPI(res.Next, taxCodes)

				resp = ChangeSubscriptionResponse{
					Current: MapSubscriptionToAPI(res.Current),
					Next:    v,
				}

				return err
			})

			return resp, err
		},
		commonhttp.JSONResponseEncoderWithStatus[ChangeSubscriptionResponse](http.StatusOK),
		httptransport.AppendOptions(
			h.Options,
			httptransport.WithOperationName("changeSubscription"),
			httptransport.WithErrorEncoder(errorEncoder()),
		)...,
	)
}
