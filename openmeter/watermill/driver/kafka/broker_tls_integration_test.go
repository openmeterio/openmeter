// tlsTestEnvVar gates the TLS integration test, which starts a real Kafka broker in Docker.
const tlsTestEnvVar = "KAFKA_TLS_INTEGRATION"

// Apache Kafka 4.0 matches the Kafka version of the confluentinc/cp-kafka:8.0.x image used in docker-compose.
// The apache/kafka image is used because cp-kafka's entrypoint insists on JKS keystore/credential files
// (KAFKA_SSL_KEYSTORE_FILENAME, ...), while apache/kafka passes KAFKA_* settings straight through and
// supports PEM keystores. The TLS listener is deliberately named EXTERNAL (protocol SSL) because the image's
// configure script demands JKS credential files whenever an advertised listener starts with "SSL://".
const tlsTestKafkaImage = "apache/kafka:4.0.0"

// TestSecurityProtocolSSLAgainstTLSOnlyBroker runs against a real single-node KRaft Kafka whose only
// client-facing listener is TLS (no SASL). Run with:
//
//	KAFKA_TLS_INTEGRATION=1 go test -run TestSecurityProtocolSSLAgainstTLSOnlyBroker -v ./openmeter/watermill/driver/kafka/
//
// The broker certificate is signed by a throwaway CA generated by the test. The CA is injected into
// the sarama config's RootCAs after createKafkaConfig (instead of via SSL_CERT_FILE, which Go ignores on
// macOS), so the production code is exercised unchanged and certificate verification stays enabled.
func TestSecurityProtocolSSLAgainstTLSOnlyBroker(t *testing.T) {
	if os.Getenv(tlsTestEnvVar) == "" {
		t.Skipf("set %s=1 to run the Kafka TLS integration test (requires Docker)", tlsTestEnvVar)
	}

	if _, err := exec.LookPath("docker"); err != nil {
		t.Skip("docker CLI not found")
	}

	ctx, cancel := context.WithTimeout(t.Context(), 4*time.Minute)
	defer cancel()

	caPEM, brokerPEM := generateTLSMaterial(t)
	broker := startTLSOnlyKafka(ctx, t, brokerPEM)

	newConfig := func(t *testing.T, protocol string) *sarama.Config {
		t.Helper()

		opts := BrokerOptions{
			KafkaConfig: config.KafkaConfiguration{Broker: broker, SecurityProtocol: protocol},
			ClientID:    "tls-it",
			Logger:      slog.New(slog.DiscardHandler),
			MetricMeter: noop.NewMeterProvider().Meter("test"),
		}

		cfg, err := opts.createKafkaConfig("publisher")
		require.NoError(t, err)

		cfg.Net.DialTimeout = 5 * time.Second
		cfg.Metadata.Retry.Max = 1
		cfg.Metadata.Retry.Backoff = 100 * time.Millisecond
		cfg.Version = sarama.V3_6_0_0

		return cfg
	}

	trustCA := func(t *testing.T, cfg *sarama.Config) {
		t.Helper()

		// Without the SSL branch in createKafkaConfig there is no TLS config to trust the CA in; the client then
		// speaks plaintext and the test fails with the EOF error from the broker (see the negative control).
		if cfg.Net.TLS.Config == nil {
			return
		}

		pool := x509.NewCertPool()
		require.True(t, pool.AppendCertsFromPEM(caPEM))
		cfg.Net.TLS.Config.RootCAs = pool
	}

	t.Run("SSL protocol publishes and consumes over TLS", func(t *testing.T) {
		cfg := newConfig(t, "SSL")
		trustCA(t, cfg)

		admin, err := sarama.NewClusterAdmin([]string{broker}, cfg)
		require.NoError(t, err)
		t.Cleanup(func() { _ = admin.Close() })

		topic := "tls-it-topic"
		require.NoError(t, admin.CreateTopic(topic, &sarama.TopicDetail{NumPartitions: 1, ReplicationFactor: 1}, false))

		producer, err := sarama.NewSyncProducer([]string{broker}, cfg)
		require.NoError(t, err)
		t.Cleanup(func() { _ = producer.Close() })

		_, _, err = producer.SendMessage(&sarama.ProducerMessage{Topic: topic, Value: sarama.StringEncoder("hello over tls")})
		require.NoError(t, err)

		consumer, err := sarama.NewConsumer([]string{broker}, cfg)
		require.NoError(t, err)
		t.Cleanup(func() { _ = consumer.Close() })

		pc, err := consumer.ConsumePartition(topic, 0, sarama.OffsetOldest)
		require.NoError(t, err)
		t.Cleanup(func() { _ = pc.Close() })

		select {
		case msg := <-pc.Messages():
			require.Equal(t, "hello over tls", string(msg.Value))
		case <-time.After(30 * time.Second):
			t.Fatal("timed out waiting for the published message")
		}
	})

	t.Run("negative control: plaintext client against TLS-only listener fails", func(t *testing.T) {
		// This is the behavior before the fix: SecurityProtocol SSL did not enable TLS.
		cfg := newConfig(t, "SSL")
		cfg.Net.TLS.Enable = false

		_, err := sarama.NewClient([]string{broker}, cfg)
		require.Error(t, err)
		require.ErrorContains(t, err, "run out of available brokers")
		t.Logf("plaintext client error: %v", err)
	})

	t.Run("certificate verification stays enabled: untrusted CA is rejected", func(t *testing.T) {
		cfg := newConfig(t, "SSL") // RootCAs left nil => system roots, which do not contain the test CA

		_, err := sarama.NewClient([]string{broker}, cfg)
		require.Error(t, err)
		require.ErrorContains(t, err, "run out of available brokers")
		t.Logf("untrusted CA error: %v", err)
	})
}

// generateTLSMaterial returns the CA certificate (PEM) and a PEM keystore (key + cert chain) for the broker.
func generateTLSMaterial(t *testing.T) (caPEM []byte, brokerPEM []byte) {
	t.Helper()

	caKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	require.NoError(t, err)

	caTmpl := &x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               pkix.Name{CommonName: "openmeter-test-ca"},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(24 * time.Hour),
		IsCA:                  true,
		BasicConstraintsValid: true,
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageCRLSign,
	}

	caDER, err := x509.CreateCertificate(rand.Reader, caTmpl, caTmpl, &caKey.PublicKey, caKey)
	require.NoError(t, err)

	caCert, err := x509.ParseCertificate(caDER)
	require.NoError(t, err)

	srvKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	require.NoError(t, err)

	srvTmpl := &x509.Certificate{
		SerialNumber: big.NewInt(2),
		Subject:      pkix.Name{CommonName: "localhost"},
		DNSNames:     []string{"localhost"},
		IPAddresses:  []net.IP{net.ParseIP("127.0.0.1"), net.ParseIP("::1")},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(24 * time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}

	srvDER, err := x509.CreateCertificate(rand.Reader, srvTmpl, caCert, &srvKey.PublicKey, caKey)
	require.NoError(t, err)

	keyDER, err := x509.MarshalPKCS8PrivateKey(srvKey)
	require.NoError(t, err)

	var buf bytes.Buffer
	require.NoError(t, pem.Encode(&buf, &pem.Block{Type: "PRIVATE KEY", Bytes: keyDER}))
	require.NoError(t, pem.Encode(&buf, &pem.Block{Type: "CERTIFICATE", Bytes: srvDER}))

	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: caDER}), buf.Bytes()
}

// startTLSOnlyKafka starts a single-node KRaft broker with one SSL listener (published on a free host
// port) and plaintext internal/controller listeners that are not published. It returns host:port.
func startTLSOnlyKafka(ctx context.Context, t *testing.T, brokerPEM []byte) string {
	t.Helper()

	l, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)

	port := l.Addr().(*net.TCPAddr).Port
	require.NoError(t, l.Close())

	pemPath := filepath.Join(t.TempDir(), "broker.pem")
	require.NoError(t, os.WriteFile(pemPath, brokerPEM, 0o644))

	name := fmt.Sprintf("openmeter-kafka-tls-it-%d", time.Now().UnixNano())

	docker := func(args ...string) string {
		t.Helper()

		out, err := exec.CommandContext(ctx, "docker", args...).CombinedOutput()
		require.NoError(t, err, "docker %s: %s", strings.Join(args, " "), out)

		return strings.TrimSpace(string(out))
	}

	env := map[string]string{
		"CLUSTER_ID":                                     "ca497efe-9f82-4b84-890b-d9969a9a2e1c",
		"KAFKA_NODE_ID":                                  "0",
		"KAFKA_PROCESS_ROLES":                            "broker,controller",
		"KAFKA_CONTROLLER_QUORUM_VOTERS":                 "0@localhost:19093",
		"KAFKA_CONTROLLER_LISTENER_NAMES":                "CONTROLLER",
		"KAFKA_INTER_BROKER_LISTENER_NAME":               "INTERNAL",
		"KAFKA_LISTENER_SECURITY_PROTOCOL_MAP":           "INTERNAL:PLAINTEXT,CONTROLLER:PLAINTEXT,EXTERNAL:SSL",
		"KAFKA_LISTENERS":                                fmt.Sprintf("INTERNAL://localhost:19092,CONTROLLER://localhost:19093,EXTERNAL://0.0.0.0:%d", port),
		"KAFKA_ADVERTISED_LISTENERS":                     fmt.Sprintf("INTERNAL://localhost:19092,EXTERNAL://localhost:%d", port),
		"KAFKA_SSL_KEYSTORE_TYPE":                        "PEM",
		"KAFKA_SSL_KEYSTORE_LOCATION":                    "/tmp/broker.pem",
		"KAFKA_SSL_CLIENT_AUTH":                          "none",
		"KAFKA_SSL_ENDPOINT_IDENTIFICATION_ALGORITHM":    "",
		"KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR":         "1",
		"KAFKA_TRANSACTION_STATE_LOG_MIN_ISR":            "1",
		"KAFKA_TRANSACTION_STATE_LOG_REPLICATION_FACTOR": "1",
		"KAFKA_GROUP_INITIAL_REBALANCE_DELAY_MS":         "0",
		"KAFKA_AUTO_CREATE_TOPICS_ENABLE":                "false",
	}

	args := []string{"create", "--name", name, "-p", fmt.Sprintf("127.0.0.1:%d:%d", port, port)}
	for k, v := range env {
		args = append(args, "-e", k+"="+v)
	}

	args = append(args, tlsTestKafkaImage)

	docker(args...)

	t.Cleanup(func() {
		if t.Failed() {
			out, _ := exec.Command("docker", "logs", "--tail", "60", name).CombinedOutput()
			t.Logf("kafka container logs:\n%s", out)
		}

		_ = exec.Command("docker", "rm", "-f", name).Run()
	})

	docker("cp", pemPath, name+":/tmp/broker.pem")
	docker("start", name)

	addr := fmt.Sprintf("localhost:%d", port)

	// Wait until the listener accepts TCP connections and the broker finished starting.
	require.Eventually(t, func() bool {
		if running, _ := exec.CommandContext(ctx, "docker", "inspect", "-f", "{{.State.Running}}", name).Output(); strings.TrimSpace(string(running)) != "true" {
			return false // container exited; the failure path below prints its logs
		}

		out, err := exec.CommandContext(ctx, "docker", "logs", "--tail", "200", name).CombinedOutput()
		if err != nil || !strings.Contains(string(out), "Kafka Server started") {
			return false
		}

		c, err := net.DialTimeout("tcp", addr, time.Second)
		if err != nil {
			return false
		}

		_ = c.Close()

		return true
	}, 2*time.Minute, time.Second, "kafka did not start")

	return addr
}
